# 工作方式与报告节奏。
#
# 这两件事以前分头写在 system（「工作方式」）与 user（「报告节奏」）里，同一句
# 「报告完调 end_done」说了两遍。现在合并成一段放 user：system 只留**不随组变化**
# 的东西（角色、输入格式、硬约束），随本次审查走的都放 user。
WORKFLOW: tuple[str, ...] = (
    # **审查是两遍，不是一遍**：先建立对整个改动的理解（它想干什么、牵扯哪些文件、
    # 相互怎么牵连），再落到每个 hunk 上逐点核对。要求「审一个 hunk 就报一个」等于
    # 要求先下结论再收集证据 —— 实测模型做不到，只能假装走一遍、最后一次性交卷
    # （见反馈文档 23 号 §十一：20 个样本里 18 个「首报轮次 = 总轮次 − 1」）
    # **第一遍只留「理解」，不留「定计划」。**
    #
    # 「定计划」那一版（要求它动手前先写下「这一趟打算怎么查」）实测**没有产出**：
    # 加了它前后两局逐轮扫过模型的思考与正文，计划类措辞 2 段 → 3 段（那 3 段
    # 还不是计划），**回头引用计划的 0 段**；6/6 个 PR 的第一轮都是
    # 「Let me start by reading the files」—— 它直接就开始读了，中间那一步
    # 从来没发生。而且它有个已知坏处：**计划一直留在上下文里会变成覆盖天花板**
    # （模型只查计划点过名的位置，计划外的视而不见）—— 这一点是 OCR 实测过、
    # 并为此专门在第 2 轮就把 plan 从提示词里剥掉的（见文档 25 号）。
    #
    # 「花多少力气可以不一样」这句留下：它是一条**判断**（别在 import、常量上
    # 也去查一遍调用方），不是一个过程步骤。
    "**第一遍 · 理解**：把 `<diff>` 通读一遍，弄清这个改动想干什么、"
    "牵扯哪些文件、它们之间怎么牵连。本组每个 hunk 都会有结论"
    "（收尾时机制会检查），但**花多少力气可以不一样** —— 把轮次用在值钱的地方",
    # 第二遍是**过程引导**：四条线索走每个 hunk，避免「四处跳着看」——
    # 实测的典型形态是读了 55 次文件、跨 26 个文件，却没有一处落到结论上
    # 四条线索用**缩进续行**放在同一个 bullet 里（与 MAIN_TASK_DIMENSIONS 同一手法）：
    # 拆成同级 bullet 会读成「和第一遍/第二遍并列的五件事」，而它们是从属于第二遍的
    "**第二遍 · 逐个 hunk 核对**：按编号从上到下。每个 hunk 都走同一条线索：\n"
    # ① 是这一版新加的，也是最要紧的一条：以前写的是「读周边上下文」——
    # 太含糊，实测模型就真的只在改动那几行附近打转。hunk 的 `lines` 属性
    # 就是它归属符号的范围，拿它直接读全文
    "   **① 先算出要读的范围，再读**：一个 `<file>` 里可能有**多个** `<hunk>`，每个 hunk 的"
    '属性 `lines="23-29"` 就是它归属符号在新文件里的行号范围。'
    "**按 `lines` 一处一处读，不要从第 1 行开始通读整个文件** —— "
    "通读既慢又读不全：实测的典型形态是「从头读两百行 → 以为这个文件看过了 → 交卷」，"
    "于是同一个文件里靠后的那几个 hunk **一眼都没看过**（这不是假设，是量出来的："
    "大大小小的组里，21 个 hunk 以上的组有六成的 hunk 从没被读过一行）。\n"
    "     **例**：`store.go` 里有两个 hunk，`lines` 分别是 `23-29` 与 `31-34` —— "
    "要读的是 **23~34 这一小段**（再带上紧邻几行看上下文），"
    "**不是** `file_read(path='store.go', start_line=1, end_line=45)`。"
    "**一个文件里有几个 hunk 就要看到几处**，不是「这个文件读过了」就算完\n"
    "   **② 往上游查调用方**：改了签名 / 返回值 / 结构体字段 / 公共常量时，"
    "用 `code_search` 找谁在调用它 —— 它回的是「路径:行号」，"
    "**照着行号读那一小段上下文就够了，同样不要通读那个文件**；"
    "判断调用方**这次改了没有**用 `file_read_diff(path)`，它给的就是那个文件的改动，"
    "比 `file_read` 更直接也更省。判断权在你 —— 我们不会预先告诉你哪些文件相关\n"
    "   **③ 往下游看影响**：改完之后**谁的行为会跟着变**？错误路径、返回值语义、"
    "并发假设、调用方依赖的隐式契约\n"
    # ④ 原先写的是「**交完才走下一个**」——要求逐 hunk 交错交卷。
    # **撤掉了**：那条要求失败了两次（第一次配 `complete` 工具语义，
    # 第二次配强制措辞），两次模型都「形式照做、时机不变」，还多花 28% 成本。
    # 根因是它和任务的自然形状相反 —— 审查本来就是「先读懂、再下结论」，
    # 而按文件读一次就同时拿到好几个 hunk 的上下文，你没法「别看 H-04」。
    # 现在把它要保的东西放回**输出契约**那一侧：
    # 同一处有几个问题就写几条评论（行号相同也行），这是「交出的形状」，
    # 不是「什么时候交」。完整论证见文档 24 号 §十一 第 10 条。
    # 这里**不写**「立刻报、别攒到最后」：那条命令式的要求实测失败过两次
    # （过程顺序类改动全败，见 WORKFLOW 上面那条注释），而它要保的东西已经在
    # 「**有结论就先交，别攒到最后**」里用**代价**说了一遍 —— 本项目实测模型对
    # 「你必须做 X」不敏感，对「不做的后果」才有反应
    "   **④ 下结论**：有问题边走边报（`report_hunks`），没问题也报一次空评论列表。"
    "**一个 hunk 走完再走下一个**，不要四处跳着看。"
    "下结论之前**把这一处再换个维度看一眼** —— 你在这一段代码上找到的第一个问题，"
    "往往不是唯一的一个（讲了并发，再问失败路径；讲了逻辑，再看命名、"
    "有没有重复实现、有没有对齐旧路径）。**报的是 high / medium 时尤其要这样**",
    # 「值得多花几轮」删掉了：轮数是不是瓶颈这件事已经**量过**（把探索轮数从
    # 5 开到 41，产出反而降），留着它等于给一条被证伪的直觉站台。
    "**跨文件一致性是本任务里最值钱的一类发现**（接口改了、实现或调用方没跟着改）"
    "—— 这类问题只有你能判断",
    "**每次探查前问自己**：这一轮是为了确认什么？查不出结果就换一条路。"
    "预算有限，但**判断没做出来之前，不要先写一条评论占位**",
    # 「调用可以合并」与「评论不可以合并」是两件事，以前这条把它们写混了：
    # 旧措辞是「同一 hunk 的多个问题可以合并到一次 report_hunks 中」，
    # 说的是**调用**可以一次带多件事，被读成了**评论**可以一段讲多件事。
    #
    # 「一条评论只讲一件事」是评测量出来的（文档 24 号 §8.2）：把 2~3 个要点
    # 塞进一段正文的评论里，62% 被判为「不是同一个关注点」；单要点的只有 27%。
    # 机理是可读性也是判定口径 —— 裁判问的是「这两条是不是同一件事」，
    # 一段讲三件事的正文，它就不是「一件事」了。
    # 这是**风险陈述**，不是节奏规定 —— 曾经写成硬要求（「交完才走下一个」），
    # 推不动、还多花 28% 成本，已撤（见 ④ 的说明）。
    # 保留是因为它说的是**后果**：这个项目实测过，模型对「你必须做 X」不敏感，
    # 对「不做的后果」才有反应。
    "**有结论就先交，别攒到最后**：report_hunks 随时可以再调，同一处也能继续补充"
    "**新**结论（重复的会被忽略）。攒着的风险是实打实的 —— 本组一旦因超时或超支"
    "结束，只在这段上下文里得出的判断不会出现在报告里",
    "**一次 report_hunks 调用可以带上多个 hunk、多条评论** —— 省的是调用次数；"
    "但**每条评论只讲一件事**：发现几个问题就写几条评论（行号相同也可以），"
    "别把几个要点、影响分析和修复建议全塞进一段正文 —— "
    "读的人分不清哪句对应哪个问题，也没法逐条回复或逐条关掉",
    # 曾经这里写的是「**同一个根因只报一次** —— 写在最能说明问题的那一处，
    # 不要跨 hunk 重复报」。**删掉的理由**：与真实评审不符 —— 生产环境的
    # 调用方只会看到贴在他那一段代码上的评论，让他去别处找同一句话是不现实的；
    # 安全问题尤其如此，同一个凭证出现在五个地方就是五处都要改。
    # 代价要说清：这会让输出条数涨（评测里 A2 那 19 条就是它造成的），
    # 换的是「每一处都有人看得见」
    "**同类问题出现在多个地方时，每一处都要报** —— 不要因为「刚才已经说过了」就跳过："
    "读的人只会看到贴在他这一段代码上的评论，被跳过的那几处看起来就像没问题",
    "**只报问题**：确认无误的代码不用写成评论（「这里没问题」「请确认…」都不是评论）",
    # 唯一一条硬要求，对应 end_done 的前置条件：它保证的是**覆盖**
    "**收尾时每个 hunk 都要有结论**：审完的用 report_hunks 报（没问题就报空评论列表），"
    "全部 hunk 都有结论之后再调 end_done —— 没报完时 end_done 会被拒绝",
)


def _t(text: str) -> str:
    """规范化模板：去掉三引号带来的首尾换行。

    让模板文件里可以自然地让闭合引号独占一行，而渲染结果与
    `"\\n".join(...)` 手写拼接逐字节一致。

    Args:
        text: 三引号模板原文

    Returns:
        去掉首尾换行的文本
    """
    return text.strip("\n")


