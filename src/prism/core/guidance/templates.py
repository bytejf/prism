def _t(text: str) -> str:
    """规范化模板：去掉三引号带来的首尾换行。

    让模板文件里可以自然地让闭合引号独占一行，而渲染结果与
    `"\\n".join(...)` 手写拼接逐字节一致。

    Args:
        text: 三引号模板原文

    Returns:
        去掉首尾换行的文本
    """
    return text.strip("\n")


